from cuda_fdm.ref import jsb_propulsion as PROP
from cuda_fdm.ref import f16_aero_data as AD
from cuda_fdm.ref.jsb_atmos import StandardAtmosphere

OUT = HERE.parent / "f16_gen.cuh"


def c(x):
    """double 을 round-trip 정확한 C 리터럴로."""
    return repr(float(x))


def arr(name, vals):
    body = ", ".join(c(v) for v in vals)
    return f"__constant__ double {name}[{len(vals)}] = {{ {body} }};\n"


# ---- property name -> C 식 (aero 컨텍스트 변수) ----
PROP2C = {
    "aero/qbar-psf": "qbar",
    "metrics/Sw-sqft": "300.0",
    "metrics/bw-ft": "30.0",
    "metrics/cbarw-ft": "11.32",
    "aero/alpha-rad": "alpha",
    "aero/beta-rad": "beta",
    "aero/bi2vel": "bi2vel",
    "aero/ci2vel": "ci2vel",
    "velocities/mach": "mach",
    "aero/function/kCLge": "kclge",
    "velocities/p-aero-rad_sec": "p_aero",
    "velocities/q-aero-rad_sec": "q_aero",
    "velocities/r-aero-rad_sec": "r_aero",
    "fcs/aileron-pos-rad": "ail_pos",
    "fcs/elevator-pos-rad": "elev_pos",
    "fcs/rudder-pos-rad": "rud_pos",
    "fcs/lef-pos-rad": "lef_pos",
    "fcs/flaperon-mix-rad": "flap_mix",
    "fcs/speedbrake-pos-rad": "sb_pos",
    "gear/gear-pos-norm": "gear_pos",
}


class TableEmitter:
    def __init__(self):
        self.decls = []
        self.count = 0

    def emit1d(self, rows):
        i = self.count; self.count += 1
        xs = [r[0] for r in rows]; ys = [r[1] for r in rows]
        self.decls.append(arr(f"T1x_{i}", xs))
        self.decls.append(arr(f"T1y_{i}", ys))
        return f"table1d(T1x_{i}, T1y_{i}, {len(xs)}, %s)"

    def emit2d(self, rowvals, colvals, data):
        i = self.count; self.count += 1
        flat = [data[r][ci] for r in range(len(rowvals)) for ci in range(len(colvals))]
        self.decls.append(arr(f"T2r_{i}", rowvals))
        self.decls.append(arr(f"T2c_{i}", colvals))
        self.decls.append(arr(f"T2d_{i}", flat))
        return (f"table2d(T2r_{i}, {len(rowvals)}, T2c_{i}, {len(colvals)}, "
                f"T2d_{i}, %s, %s)")


def emit_aero(te):
    """40 함수를 6개 축합으로. 반환: (아래 6줄) 를 담은 C 코드 문자열."""
    axes_order = ["DRAG", "SIDE", "LIFT", "ROLL", "PITCH", "YAW"]
    lines = []
    for ax in axes_order:
        lines.append(f"  // ===== {ax} =====")
        lines.append(f"  s = 0.0;")
        for f in AD.AXES[ax]:
            terms = [PROP2C[p] for p in f["factors"]]
            expr = " * ".join(terms) if terms else "1.0"
            if f["value"] is not None:
                expr += f" * {c(f['value'])}"
            t = f["table"]
            if t is not None:
                if t["type"] == "1d":
                    call = te.emit1d(t["rows"]) % PROP2C[t["indep"]]
                else:
                    call = te.emit2d(t["rowvals"], t["colvals"], t["data"]) % (
                        PROP2C[t["row_indep"]], PROP2C[t["col_indep"]])
                expr += f" * {call}"
            lines.append(f"  s += {expr};   // {f['name']}")
        lines.append(f"  *{ax} = s;")
    return "\n".join(lines)


def main():
    atm = StandardAtmosphere()
    SLGRAVITY = FR.GM / (FR.SEMI_MAJOR * FR.SEMI_MAJOR)
    import math
    STD_SL_SOUNDSPEED = math.sqrt(C.SHRatio * C.Reng * C.StdDaySLtemperature)

    te = TableEmitter()
    aero_body = emit_aero(te)

    # 엔진 테이블 (Table2D(rowvals=mach, colvals=cols, data))
    eng_idle = te.emit2d(PROP._IDLE_MACH, PROP._COLS, PROP._IDLE)
    eng_mil = te.emit2d(PROP._MIL_MACH, PROP._COLS, PROP._MIL)
    eng_aug = te.emit2d(PROP._AUG_MACH, PROP._COLS, PROP._AUG)
    # FCS 게인 테이블
    fcs_ail = te.emit1d([(0.0, 1.0), (1.0, 0.15)])
    fcs_elev = te.emit1d([(-0.5236, 0.0), (-0.5, 0.11), (0.0, 1.0), (0.5, 0.11), (0.5236, 0.0)])
    fcs_yaw = te.emit1d([(80.0, 0.0), (100.0, 15.0), (150.0, 100.0)])
    kclge = te.emit1d(AD.TOP_FUNCTIONS["aero/function/kCLge"]["table"]["rows"])

    L = []
    W = L.append
    W("// AUTO-GENERATED by gen_c_fdm.py — do not edit.")
    W("// F16 JSBSim v1.0.0 상수/테이블/공력 평탄화 (검증된 jsb_*.py ref 기준).")
    W("#ifndef F16_GEN_CUH")
    W("#define F16_GEN_CUH")
    W("")
    W("// __constant__/__device__ 는 host 컴파일시 fdm.cuh 에서 빈 매크로로 정의.")
    W("")
    W("// ---------------- 물리/단위 상수 ----------------")
    for nm, v in [
        ("RADTODEG", C.RADTODEG), ("DEGTORAD", C.DEGTORAD),
        ("KTSTOFPS", C.KTSTOFPS), ("FPSTOKTS", C.FPSTOKTS),
        ("INCHTOFT", C.INCHTOFT), ("FTTOM", C.FTTOM),
        ("SLUGTOLB", C.SLUGTOLB), ("LBTOSLUG", C.LBTOSLUG),
        ("KGTOSLUG", C.KGTOSLUG),
        ("Rstar", C.Rstar), ("Mair", C.Mair), ("g0", C.g0), ("Reng", C.Reng),
        ("SHRatio", C.SHRatio), ("StdDaySLtemperature", C.StdDaySLtemperature),
        ("StdDaySLpressure", C.StdDaySLpressure),
        ("SutherlandConstant", C.SutherlandConstant), ("Beta_visc", C.Beta_visc),
        ("EarthRadius", C.EarthRadius),
        ("SEMI_MAJOR", FR.SEMI_MAJOR), ("SEMI_MINOR", FR.SEMI_MINOR),
        ("GM", FR.GM), ("J2const", FR.J2), ("ROTATION_RATE", FR.ROTATION_RATE),
        ("EC", FR.EC), ("EC2", FR.EC2), ("E2", FR.E2), ("CCONST", FR.CCONST),
        ("SLGRAVITY", SLGRAVITY), ("SEA_LEVEL_RADIUS", FR.SEMI_MAJOR),
        ("STD_SL_SOUNDSPEED", STD_SL_SOUNDSPEED),
    ]:
        W(f"__constant__ double {nm} = {c(v)};")
    W("")
    W("// ---------------- 표준대기 파생 (지오포텐셜 층상 ISA) ----------------")
    W(f"#define NATM {atm.nrows}")
    W(arr("ATM_ALT", atm.alts).rstrip())
    W(arr("ATM_TMP", atm.temps).rstrip())
    W(arr("ATM_LAPSE", atm.lapse).rstrip())
    W(arr("ATM_PBRK", atm.pbrk).rstrip())
    atm._StandardAtmosphere__init_density_bp()
    W(arr("ATM_DBRK", atm.dbrk).rstrip())
    W("")
    W("// ---------------- 엔진(F100-PW-229) 상수 ----------------")
    for nm, v in [
        ("MILTHRUST", PROP.MILTHRUST), ("MAXTHRUST", PROP.MAXTHRUST),
        ("BYPASSRATIO", PROP.BYPASSRATIO), ("TSFC", PROP.TSFC), ("ATSFC", PROP.ATSFC),
        ("IDLEN1", PROP.IDLEN1), ("IDLEN2", PROP.IDLEN2),
        ("MAXN1", PROP.MAXN1), ("MAXN2", PROP.MAXN2),
        ("BLEEDDEMAND", PROP.BLEEDDEMAND), ("IdleFF", PROP.IdleFF),
    ]:
        W(f"__constant__ double {nm} = {c(v)};")
    W("")
    W("// ---------------- 테이블 데이터 ----------------")
    for d in te.decls:
        W(d.rstrip())
    W("")
    W("// ---------------- 엔진 thrust 테이블 접근 매크로 ----------------")
    W(f"#define ENG_IDLE(mach, densalt) ({eng_idle % ('(mach)', '(densalt)')})")
    W(f"#define ENG_MIL(mach, densalt)  ({eng_mil % ('(mach)', '(densalt)')})")
    W(f"#define ENG_AUG(mach, densalt)  ({eng_aug % ('(mach)', '(densalt)')})")
    W("")
    W("// ---------------- FCS 게인 테이블 매크로 ----------------")
    W(f"#define FCS_AIL_SPEED(mach) ({fcs_ail % '(mach)'})")
    W(f"#define FCS_ELEV_SCHED(alpha) ({fcs_elev % '(alpha)'})")
    W(f"#define FCS_YAW_RATE(vg) ({fcs_yaw % '(vg)'})")
    W(f"#define KCLGE(hb) ({kclge % '(hb)'})")
    W("")
    W("// ---------------- 공력 40함수 평탄화 ----------------")
    W("HOSTDEV void f16_aero(")
    W("    double qbar, double alpha, double beta, double mach,")
    W("    double bi2vel, double ci2vel, double kclge,")
    W("    double p_aero, double q_aero, double r_aero,")
    W("    double ail_pos, double elev_pos, double rud_pos, double lef_pos,")
    W("    double flap_mix, double sb_pos, double gear_pos,")
    W("    double* DRAG, double* SIDE, double* LIFT,")
    W("    double* ROLL, double* PITCH, double* YAW) {")
    W("  double s;")
    W(aero_body)
    W("}")
    W("")
    W("#endif // F16_GEN_CUH")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}  ({len(L)} lines, {te.count} tables)")


if __name__ == "__main__":
    main()
